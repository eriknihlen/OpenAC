    public static bool TryLoadNav(
        string text,
        NavigationSettings target,
        ISpellCatalog spells,
        out string error)
    {
        ArgumentNullException.ThrowIfNull(target);
        ArgumentNullException.ThrowIfNull(spells);
        try
        {
            var cursor = new Cursor(SplitLines(text));
            var navs = new Dictionary<string, (string NavType, List<RouteWaypoint> Nodes,
                uint FollowTargetId, string FollowTargetName)>(StringComparer.Ordinal);
            cursor.SkipBlank();
            while (cursor.L < cursor.Lines.Length)
            {
                Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
                if (!lead.Success)
                    throw cursor.Error("expected 'NAV:' (or a STATE: rule section, refused for a route load).");
                if (lead.Groups["type"].Value == "NAV:")
                {
                    ReadNavBlock(cursor, navs, spells);
                    continue;
                }
                throw cursor.Error(
                    "found a STATE: rule section — this is a Meta profile "
                    + "(possibly with an embedded nav), not a stand-alone "
                    + "route; load it from the metas/ folder instead.");
            }
            if (navs.Count == 0)
                throw cursor.Error(
                    "no NAV: block found — this looks like a Meta profile that belongs "
                    + "in the metas/ folder, not a route.");
            var (navType, nodes, followId, followName) = navs.First().Value;
            ApplyNavBody(target, navType, nodes, followId, followName);
            error = string.Empty;
            return true;
        }
        catch (Exception exception) when (exception is FormatException or RegexMatchTimeoutException)
        {
            error = exception.Message;
            return false;
        }
    }

    public static string SaveNav(NavigationSettings source)
    {
        ArgumentNullException.ThrowIfNull(source);
        var lines = new List<string> { NavOutputHeader };
        WriteNavBlock(lines, "nav0", source);
        return string.Join("\r\n", lines) + "\r\n";
    }

    private static void ReadNavBlock(
        Cursor cursor,
        Dictionary<string, (string NavType, List<RouteWaypoint> Nodes, uint FollowTargetId, string FollowTargetName)> navs,
        ISpellCatalog spells)
    {
        Match header = LeadIn.Match(cursor.Lines[cursor.L]);
        string headerRemainder = TrailingComment.Replace(
            cursor.Lines[cursor.L][(header.Groups["tabs"].Length + "NAV:".Length)..],
            string.Empty);
        Match nav = NavHeader.Match(headerRemainder);
        if (!nav.Success)
        {
            throw cursor.Error(
                "'NAV:' must be followed by a tag literal and a nav type (circular/linear/once/follow).");
        }
        string tag = nav.Groups["l"].Value;
        string navType = nav.Groups["l2"].Value;
        cursor.L++;
        cursor.SkipBlank();

        var nodes = new List<RouteWaypoint>();
        uint followTargetId = 0u;
        string followTargetName = string.Empty;
        while (true)
        {
            cursor.SkipBlank();
            if (cursor.L >= cursor.Lines.Length)
                break;
            Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
            if (lead.Success)
                break;
            Match nodeOp = AnyNavNodeType.Match(cursor.Lines[cursor.L]);
            if (!nodeOp.Success)
                throw cursor.Error("expected a nav node line (one tab, then a node keyword).");
            string keyword = nodeOp.Groups["type"].Value;
            cursor.C = nodeOp.Length;
            string remainder = cursor.RemainderOfCurrentLine();
            cursor.L++;
            Match args = NavArgs[keyword].Match(remainder);
            if (!args.Success)
                throw cursor.Error($"'{keyword}' arguments do not match the expected shape.");

            if (keyword == "flw")
            {
                followTargetId = ParseHexAsUInt(args.Groups["h"].Value);
                followTargetName = StripDelimiters(args.Groups["s"].Value);
                continue;
            }
            nodes.Add(ReadNavNode(keyword, args, spells));
        }
        navs[tag] = (navType, nodes, followTargetId, followTargetName);
    }

    private static RouteWaypoint ReadNavNode(string keyword, Match args, ISpellCatalog spells)
    {
        double x = args.Groups["d"].Success ? ParseDouble(args.Groups["d"].Value) : 0d;
        double y = args.Groups["d2"].Success ? ParseDouble(args.Groups["d2"].Value) : 0d;
        double z = args.Groups["d3"].Success ? ParseDouble(args.Groups["d3"].Value) : 0d;
        var waypoint = new RouteWaypoint
        {
            Type = NodeWaypointType(keyword),
            Position = new PluginNavigationPosition(0u, x, y, z, 0f, IsOutdoor: true),
        };
        switch (keyword)
        {
            case "prt":
                waypoint.ObjectId = ParseHexAsUInt(args.Groups["h"].Value);
                break;
            case "rcl":
                waypoint.RecallSpellName = StripDelimiters(args.Groups["s"].Value);
                waypoint.RecallSpellId = ResolveSpellIdByName(spells, waypoint.RecallSpellName);
                break;
            case "pau":
                waypoint.DurationMilliseconds = checked((int)Math.Round(
                    ParseDouble(args.Groups["d4"].Value),
                    MidpointRounding.AwayFromZero));
                break;
            case "cht":
                waypoint.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "vnd":
                waypoint.ObjectId = ParseHexAsUInt(args.Groups["h"].Value);
                waypoint.ObjectName = StripDelimiters(args.Groups["s"].Value);
                break;
            case "ptl" or "tlk":
                waypoint.ObjectName = StripDelimiters(args.Groups["s"].Value);
                waypoint.LegacyObjectClass = ParseInt(args.Groups["i"].Value);
                waypoint.LegacyReferenceValid = true;
                waypoint.ReferencePosition = new PluginNavigationPosition(
                    0u,
                    ParseDouble(args.Groups["d4"].Value),
                    ParseDouble(args.Groups["d5"].Value),
                    ParseDouble(args.Groups["d6"].Value),
                    0f,
                    IsOutdoor: true);
                break;
            case "jmp":
                waypoint.JumpHeadingDegrees = checked((float)ParseDouble(args.Groups["d4"].Value));
                waypoint.JumpRun = StripDelimiters(args.Groups["s"].Value) == "True";
                waypoint.JumpChargeMilliseconds = checked((int)Math.Round(
                    ParseDouble(args.Groups["d5"].Value),
                    MidpointRounding.AwayFromZero));
                break;
        }
        return waypoint;
    }

    private static void ApplyNavBody(
        NavigationSettings target,
        string navType,
        List<RouteWaypoint> nodes,
        uint followTargetId,
        string followTargetName)
    {
        target.Mode = navType switch
        {
            "circular" => RouteMode.Circular,
            "linear" => RouteMode.Linear,
            "follow" => RouteMode.Target,
            "once" => RouteMode.Once,
            _ => throw new FormatException($"unknown nav type '{navType}'."),
        };
        target.Waypoints.Clear();
        if (target.Mode == RouteMode.Target)
        {
            target.FollowTargetObjectId = followTargetId;
            target.FollowTargetName = followTargetName;
            return;
        }
        target.Waypoints.AddRange(nodes);
    }

