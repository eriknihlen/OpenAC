    private sealed class Cursor(string[] lines)
    {
        public string[] Lines { get; } = lines;
        public int L { get; set; }
        public int C { get; set; }

        public FormatException Error(string message) =>
            new($"line {Math.Min(L + 1, Lines.Length)}: {message}");

        public void SkipBlank()
        {
            while (L < Lines.Length && BlankOrCommentLine.IsMatch(Lines[L]))
                L++;
        }

        public string RemainderOfCurrentLine() => TrailingComment.Replace(
            Lines[L][Math.Min(C, Lines[L].Length)..], string.Empty);
    }

