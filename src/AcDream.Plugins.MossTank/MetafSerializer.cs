    private static string[] SplitLines(string text) => (text ?? string.Empty)
        .Replace("\r\n", "\n", StringComparison.Ordinal)
        .Split('\n');

    private static string StripDelimiters(string value) =>
        value.Length >= 2 ? value[1..^1] : string.Empty;

    private static int ParseInt(string text) => int.Parse(
        text, NumberStyles.Integer, CultureInfo.InvariantCulture);

    private static double ParseDouble(string text) => double.Parse(
        text, NumberStyles.Float, CultureInfo.InvariantCulture);

    private static int ParseHexAsInt(string text)
    {
        uint unsigned = uint.Parse(text, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        return unchecked((int)unsigned);
    }

    private static uint ParseHexAsUInt(string text) =>
        uint.Parse(text, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

    private static string FormatNumber(double value) => value.ToString(CultureInfo.InvariantCulture);

    private static string FormatHex(double value) => unchecked((uint)checked((int)value))
        .ToString("X8", CultureInfo.InvariantCulture);

    private static string FormatHex(uint value) => value.ToString("X8", CultureInfo.InvariantCulture);

    private static uint ResolveSpellIdByName(ISpellCatalog spells, string name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return 0u;
        foreach (PluginSpellInfo spell in spells.KnownSelfBuffs)
        {
            if (spell.Name.Equals(name, StringComparison.OrdinalIgnoreCase))
                return spell.SpellId;
        }
        foreach (PluginSpellInfo spell in spells.KnownCombatSpells)
        {
            if (spell.Name.Equals(name, StringComparison.OrdinalIgnoreCase))
                return spell.SpellId;
        }
        return 0u;
    }

