    // STATE / Rule (IF:/DO:) reading — State.ImportFromMetAF, Rule.ImportFromMetAF.
    // ------------------------------------------------------------------

    private static void ReadState(Cursor cursor, MetaProfile profile)
    {
        Match header = LeadIn.Match(cursor.Lines[cursor.L]);
        string headerRemainder = TrailingComment.Replace(
            cursor.Lines[cursor.L][(header.Groups["tabs"].Length + "STATE:".Length)..],
            string.Empty);
        Match name = Regex.Match(headerRemainder, $@"^\s+(?<s>{S})$");
        if (!name.Success)
            throw cursor.Error("'STATE:' must be followed by a delimited string name.");
        string stateName = StripDelimiters(name.Groups["s"].Value);
        cursor.L++;

        int rulesRead = 0;
        cursor.SkipBlank();
        while (cursor.L < cursor.Lines.Length)
        {
            Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
            if (!lead.Success)
                throw cursor.Error("expected 'STATE:', 'IF:', or 'NAV:'.");
            if (lead.Groups["type"].Value is "STATE:" or "NAV:")
                break;
            if (lead.Groups["type"].Value != "IF:")
                throw cursor.Error("expected an 'IF:' line to start a new Rule.");

            cursor.C = 0;
            MetaCondition condition = ReadTopLevelCondition(cursor);
            MetaAction action = ReadTopLevelAction(cursor);
            profile.Rules.Add(new MetaRule
            {
                State = stateName,
                Condition = condition,
                Action = action,
                Enabled = true,
            });
            rulesRead++;
            cursor.SkipBlank();
        }
        if (rulesRead == 0)
            throw cursor.Error($"state '{stateName}' has no rules (every state needs at least one).");
    }

    private static MetaCondition ReadTopLevelCondition(Cursor cursor)
    {
        cursor.SkipBlank();
        Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
        if (!lead.Success || lead.Groups["type"].Value != "IF:")
            throw cursor.Error("expected an 'IF:' line.");
        cursor.C = lead.Length;
        Match op = AnyConditionOp.Match(cursor.Lines[cursor.L][cursor.C..]);
        if (!op.Success)
            throw cursor.Error("expected a Condition operation after 'IF:'.");
        cursor.C += op.Groups["op"].Index + op.Groups["op"].Length;
        return ReadCondition(cursor, op.Groups["op"].Value, ConditionDepth);
    }

    private static MetaAction ReadTopLevelAction(Cursor cursor)
    {
        cursor.SkipBlank();
        Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
        if (!lead.Success || lead.Groups["type"].Value != "DO:")
            throw cursor.Error("expected a 'DO:' line.");
        cursor.C = lead.Length;
        Match op = AnyActionOp.Match(cursor.Lines[cursor.L][cursor.C..]);
        if (!op.Success)
            throw cursor.Error("expected an Action operation after 'DO:'.");
        cursor.C += op.Groups["op"].Index + op.Groups["op"].Length;
        return ReadAction(cursor, op.Groups["op"].Value, ActionDepth);
    }


    private static MetaCondition ReadCondition(Cursor cursor, string keyword, int depth)
    {
        if (keyword == "Not")
        {
            var not = new MetaCondition { Kind = MetaConditionKind.Not };
            string notRemainder = cursor.Lines[cursor.L][cursor.C..];
            Match nested = AnyConditionOp.Match(notRemainder);
            if (!nested.Success)
                throw cursor.Error("'Not' must be followed by a Condition operation on the same line.");
            cursor.C += nested.Groups["op"].Index + nested.Groups["op"].Length;
            not.Children.Add(ReadCondition(cursor, nested.Groups["op"].Value, depth));
            return not;
        }

        var value = new MetaCondition { Kind = ConditionKind(keyword) };
        string remainder = cursor.RemainderOfCurrentLine();
        cursor.L++;
        Regex argRegex = ConditionArgs[keyword];
        Match args = argRegex.Match(remainder);
        if (!args.Success)
            throw cursor.Error($"'{keyword}' arguments do not match the expected shape.");

        switch (keyword)
        {
            case "ChatMatch":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "MainSlotsLE" or "SecsInStateGE" or "PSecsInStateGE" or "BuPercentGE":
                value.Number = ParseInt(args.Groups["i"].Value);
                break;
            case "ItemCountLE" or "ItemCountGE":
                value.Number = ParseInt(args.Groups["i"].Value);
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "MobsInDist_Name":
                value.Number = ParseInt(args.Groups["i"].Value);
                value.SecondaryNumber = ParseDouble(args.Groups["d"].Value);
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "MobsInDist_Priority":
                value.Number = ParseInt(args.Groups["i"].Value);
                value.SecondaryNumber = ParseDouble(args.Groups["d"].Value);
                value.TertiaryNumber = ParseInt(args.Groups["i2"].Value);
                break;
            case "NoMobsInDist" or "DistToRteGE":
                value.Number = ParseDouble(args.Groups["d"].Value);
                break;
            case "BlockE" or "CellE":
                value.Number = ParseHexAsInt(args.Groups["h"].Value);
                break;
            case "SecsOnSpellGE":
                value.SecondaryNumber = ParseInt(args.Groups["i"].Value);
                value.Number = ParseInt(args.Groups["i2"].Value);
                break;
            case "Expr":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "ChatCapture":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                value.SecondaryText = StripDelimiters(args.Groups["s2"].Value);
                break;
            case "All" or "Any":
                ReadNestedConditions(cursor, value, depth);
                break;
        }
        return value;
    }

    private static void ReadNestedConditions(Cursor cursor, MetaCondition parent, int depth)
    {
        while (true)
        {
            cursor.SkipBlank();
            if (cursor.L >= cursor.Lines.Length)
                throw cursor.Error("hit end-of-file inside an All/Any condition.");
            Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
            if (lead.Success)
            {
                if (lead.Groups["type"].Value == "DO:")
                    return;
                throw cursor.Error("missing 'DO:' to close this Rule.");
            }
            Match op = AnyConditionOp.Match(cursor.Lines[cursor.L]);
            if (!op.Success)
                throw cursor.Error("expected a Condition operation or 'DO:'.");
            int tabs = op.Groups["tabs"].Length;
            if (tabs <= ConditionDepth)
                throw cursor.Error("not tabbed in enough to be inside an All/Any condition.");
            if (tabs <= depth)
                return; // this line belongs to an ancestor All/Any, not us.
            if (tabs > depth + 1)
                throw cursor.Error("tabbed in too far inside an All/Any condition.");
            cursor.C = op.Groups["op"].Index + op.Groups["op"].Length;
            parent.Children.Add(ReadCondition(cursor, op.Groups["op"].Value, depth + 1));
        }
    }


    private static MetaAction ReadAction(Cursor cursor, string keyword, int depth)
    {
        var value = new MetaAction { Kind = ActionKind(keyword) };
        string remainder = cursor.RemainderOfCurrentLine();
        cursor.L++;
        Regex argRegex = ActionArgs[keyword];
        Match args = argRegex.Match(remainder);
        if (!args.Success)
            throw cursor.Error($"'{keyword}' arguments do not match the expected shape.");

        switch (keyword)
        {
            case "SetState" or "Chat" or "DoExpr" or "ChatExpr":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "CallState":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                value.SecondaryText = StripDelimiters(args.Groups["s2"].Value);
                break;
            case "SetWatchdog":
                value.Number = ParseDouble(args.Groups["d"].Value);
                value.SecondaryNumber = ParseDouble(args.Groups["d2"].Value);
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "GetOpt" or "SetOpt" or "CreateView":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                value.SecondaryText = StripDelimiters(args.Groups["s2"].Value);
                break;
            case "DestroyView":
                value.Text = StripDelimiters(args.Groups["s"].Value);
                break;
            case "EmbedNav":
                value.SecondaryText = args.Groups["l"].Value; // tag
                value.Text = StripDelimiters(args.Groups["s"].Value); // display name (temp)
                break;
            case "DoAll":
                ReadNestedActions(cursor, value, depth);
                break;
        }
        return value;
    }

    private static void ReadNestedActions(Cursor cursor, MetaAction parent, int depth)
    {
        while (true)
        {
            cursor.SkipBlank();
            if (cursor.L >= cursor.Lines.Length)
                return; // DoAll may legally be the last thing in the file.
            Match lead = LeadIn.Match(cursor.Lines[cursor.L]);
            if (lead.Success)
                return; // STATE:/IF:/DO:/NAV: all end this DoAll.
            Match op = AnyActionOp.Match(cursor.Lines[cursor.L]);
            if (!op.Success)
                throw cursor.Error("expected an Action operation.");
            int tabs = op.Groups["tabs"].Length;
            if (tabs <= ActionDepth)
                throw cursor.Error("not tabbed in enough to be inside a DoAll action.");
            if (tabs <= depth)
                return;
            if (tabs > depth + 1)
                throw cursor.Error("tabbed in too far inside a DoAll action.");
            cursor.C = op.Groups["op"].Index + op.Groups["op"].Length;
            parent.Children.Add(ReadAction(cursor, op.Groups["op"].Value, depth + 1));
        }
    }

    private static void ResolveEmbeddedNavs(
        MetaProfile profile,
        IReadOnlyDictionary<string, (string NavType, List<RouteWaypoint> Nodes, uint FollowTargetId, string FollowTargetName)> navs)
    {
        foreach (MetaRule rule in profile.Rules)
            ResolveEmbeddedNavs(rule.Action, navs);
    }

    private static void ResolveEmbeddedNavs(
        MetaAction action,
        IReadOnlyDictionary<string, (string NavType, List<RouteWaypoint> Nodes, uint FollowTargetId, string FollowTargetName)> navs)
    {
        if (action.Kind == MetaActionKind.LoadEmbeddedNavigationRoute)
        {
            string tag = action.SecondaryText;
            string displayName = action.Text;
            action.SecondaryText = displayName;
            action.Text = string.Empty;
            action.EmbeddedRoute = navs.TryGetValue(tag, out var nav)
                ? BuildNavSettings(nav.NavType, nav.Nodes, nav.FollowTargetId, nav.FollowTargetName)
                : new NavigationSettings();
        }
        foreach (MetaAction child in action.Children)
            ResolveEmbeddedNavs(child, navs);
    }

    private static NavigationSettings BuildNavSettings(
        string navType,
        List<RouteWaypoint> nodes,
        uint followTargetId,
        string followTargetName)
    {
        var settings = new NavigationSettings();
        ApplyNavBody(settings, navType, nodes, followTargetId, followTargetName);
        return settings;
    }

