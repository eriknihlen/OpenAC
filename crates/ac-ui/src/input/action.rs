//! The game's input actions: what a key, button or wheel step asks for.
//! The names are the ones the key-binding file stores, so they keep their
//! original spelling (`UseQuickSlot_1`, `LOGOUT`).

macro_rules! input_actions {
    ($($name:ident,)+) => {
        /// One input action (`None` is the unbound sentinel).
        #[allow(non_camel_case_types, clippy::upper_case_acronyms, missing_docs)]
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
        pub enum InputAction {
            #[default]
            $($name,)+
        }

        impl InputAction {
            /// Every action, in declaration order.
            pub const ALL: &'static [InputAction] = &[$(InputAction::$name,)+];

            /// The action's stored name.
            #[must_use]
            pub fn name(self) -> &'static str {
                match self {
                    $(InputAction::$name => stringify!($name),)+
                }
            }

            /// The action a stored name names (exact spelling).
            #[must_use]
            pub fn from_name(name: &str) -> Option<Self> {
                match name {
                    $(stringify!($name) => Some(InputAction::$name),)+
                    _ => None,
                }
            }
        }
    };
}

