impl std::fmt::Display for InputAction {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.name())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_round_trip_and_none_is_the_default() {
        assert_eq!(InputAction::default(), InputAction::None);
        for &action in InputAction::ALL {
            assert_eq!(InputAction::from_name(action.name()), Some(action));
        }
        assert_eq!(InputAction::ALL.len(), 333);
        assert_eq!(InputAction::UseQuickSlot_1.name(), "UseQuickSlot_1");
        assert_eq!(InputAction::from_name("LOGOUT"), Some(InputAction::LOGOUT));
        assert_eq!(InputAction::from_name("logout"), None);
    }
}
