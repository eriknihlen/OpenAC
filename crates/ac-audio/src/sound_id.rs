    #[test]
    fn every_retail_sound_has_its_exact_value() {
        for &(name, value) in GOLDEN {
            let id = SoundId::from_u32(value).unwrap_or_else(|| panic!("{name} missing"));
            assert_eq!(id.name(), name);
            assert_eq!(id.value(), value);
        }
    }

    #[test]
    fn declares_nothing_retail_does_not() {
        let mut expected: Vec<&str> = GOLDEN.iter().map(|g| g.0).collect();
        let mut actual: Vec<&str> = SoundId::ALL.iter().map(|a| a.1).collect();
        expected.sort_unstable();
        actual.sort_unstable();
        assert_eq!(expected, actual);
    }

    #[test]
    fn covers_the_dense_retail_range_with_no_gaps() {
        assert_eq!(SoundId::ALL.len(), 205);
        for (i, (id, _)) in SoundId::ALL.iter().enumerate() {
            assert_eq!(id.value(), i as u32);
        }
        assert_eq!(SoundId::ALL[204].0.value(), 0xCC);
        assert_eq!(SoundId::from_u32(0xCD), None);
    }
