//! The sound types a sound table is keyed by.

macro_rules! sound_ids {
    ($($variant:ident = $value:literal => $name:literal,)*) => {
        /// A sound type: the key a sound table stores its waves under, and
        /// what the server's sound event and the animation hooks name. The
        /// values are dense from 0 to `0xCC`.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        #[repr(u32)]
        #[allow(missing_docs)]
        pub enum SoundId {
            $($variant = $value,)*
        }

        impl SoundId {
            /// Every sound type with the game's own name for it, in value order.
            pub const ALL: &'static [(SoundId, &'static str)] = &[$((SoundId::$variant, $name),)*];

            /// The sound type with this value, if it is one.
            #[must_use]
            pub fn from_u32(value: u32) -> Option<Self> {
                match value {
                    $($value => Some(SoundId::$variant),)*
                    _ => None,
                }
            }

            /// The game's own name for the sound type (`UI_EnterPortal`, ...).
            #[must_use]
            pub fn name(self) -> &'static str {
                match self {
                    $(SoundId::$variant => $name,)*
                }
            }
        }
    };
}

